import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'

test('browser bundle switches the DSH 0.2 conversation slot to the knowledge workspace', async () => {
  const source = await readFile(new URL('../lib/client.js', import.meta.url), 'utf8')
  assert.match(source, /window\.__ModuleLoader__\.load/)
  assert.match(source, /sidebar\.footer\.action/)
  assert.match(source, /managementAvailable/)
  assert.match(source, /managementPath/)
  assert.match(source, /\\u8FD9\\u53F0 DSH \\u672A\\u542F\\u7528/)
  assert.match(source, /\\u91CD\\u8BD5/)
  assert.doesNotMatch(source, /return query\.length === 0 \? "\/knowledge"/)
  assert.match(source, /name:\s*"main\.conversation"/)
  assert.match(source, /priority:\s*-1/)
  assert.match(source, /ltx-jc-rag-workspace/)
  assert.match(source, /ltx-jc-rag-workspace-title/)
  assert.match(source, /\\u8FD4\\u56DE\\u5BF9\\u8BDD/)
  assert.doesNotMatch(source, /ltx-jc-rag-overlay|ltx-jc-rag-mask/)
  assert.doesNotMatch(source, /ResizeObserver|PANEL_SIZE_KEY/)
  assert.match(source, /settings\.plugins\.tab/)
  assert.match(source, /ltx-jc-rag-connection/)
  assert.match(source, /id:\s*KNOWLEDGE_SETTINGS_NAMESPACE/)
  assert.match(source, /ltx-jc-rag-settings-card/)
  assert.match(source, /ltx-jc-rag-auto-mount-toggle/)
  assert.match(source, /remoteToken/)
  assert.match(source, /autoMountDefaultKnowledgeBase/)
  assert.match(source, /\/ltx-jc-rag-control\/v1\/connection/)
  assert.match(source, /CONNECTION_CONTROL_PATH/)
  assert.doesNotMatch(source, /settings\.mutate/)
  assert.doesNotMatch(source, /settingsScope/)
  assert.match(source, /theme\/change/)
  assert.match(source, /host-theme-ready/)
  assert.match(source, /createKnowledgeHostTheme/)
  assert.match(source, /getComputedStyle\(document\.body\)/)
  assert.match(source, /--knowledge-accent/)
  assert.match(source, /appearance:\s*none/)
  assert.doesNotMatch(source, /accent-color:/)
  assert.match(source, /\.ltx-jc-rag-source-picker input:checked/)
  assert.doesNotMatch(source, /rgba\(51,\s*92,\s*255/)
})
